import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, isAbsolute, resolve as resolvePath } from 'node:path';
import { hasWidget, type RJSFSchema } from '@rjsf/utils';
import { createRjsfRegistry, type WidgetRegistry } from '@schemastud/seam';
import { KNOWN_CONTEXTS, type FrameContext } from './contexts';
import { createFrameRegistry } from './kit';
import type { FormMode } from './types';
import { FRAME_READS } from './wireReaders';
export { FRAME_READS } from './wireReaders';

// =============================================================================
// The frame vocabulary (ruling 05 §2; ticket 33). What a host's kits bind, per name and context, written once by
// `frame-vocabulary` and read by laravel-frame's `WidgetVocabulary`. Node-only and build-time: this module is the
// `@schemastud/frame/vocabulary` subpath, never the app's root.
// =============================================================================

/** A node type RJSF's `hasWidget` is asked about, in the sorted order `stock` lists them. */
type NodeType = 'array' | 'boolean' | 'integer' | 'number' | 'string';
const NODE_TYPES: readonly NodeType[] = ['array', 'boolean', 'integer', 'number', 'string'];

/** One registration as the file writes it: its scope (absent = unscoped) and, for a stock name, its node types. */
export interface VocabularyRegistration {
    contexts?: FrameContext[];
    stock?: NodeType[];
}

export type FrameReaders = Readonly<
    Record<
        `${'manifest' | 'resource-entry' | 'context-block' | 'schema-keywords'}:${string}`,
        (...args: never[]) => unknown
    >
>;

export interface FrameVocabulary {
    $comment: string;
    version: 1;
    contexts: FrameContext[];
    formModes: FormMode[];
    reserved: string[];
    /** Each name's registrations in the order they win. */
    widgets: Record<string, VocabularyRegistration[]>;
    /** Name → the contexts where two kits bind it and their answers differ. Absent when there are none. */
    conflicts?: Record<string, FrameContext[]>;
    /** Sorted union of Frame and host reader modules, as <group>:<key>. */
    reads?: string[];
}

/** One kit's host registrations: what that kit is handed as `widgets`. */
export type KitWidgets = (registry: WidgetRegistry) => void;

const COMMENT = 'GENERATED by frame-vocabulary. Do not edit; run `pnpm frame:vocabulary --write`.';

/** Every form mode, exhaustively: a mode added to `FormMode` and missing here fails tsc. */
const FORM_MODE_SET = { enriched: true, bare: true } as const satisfies Record<FormMode, true>;
const FORM_MODES = Object.keys(FORM_MODE_SET) as FormMode[];

/** Class-level names that are not registry widgets (ruling 01 §4). */
const RESERVED = ['row-actions'];

const KNOWN = new Set<string>(KNOWN_CONTEXTS);

/** The stock-name resolver: seam's RJSF registry (ticket 20), never a copy of RJSF's own map. */
function stockTypesFor(widgets: ReturnType<typeof createRjsfRegistry>['widgets']) {
    return (name: string): NodeType[] =>
        NODE_TYPES.filter((type) => {
            try {
                return hasWidget({ type } as RJSFSchema, name, widgets);
            } catch {
                return false;
            }
        });
}

/** One kit's registrations, as the file writes them, by name. Throws on a context frame does not know. */
function kitRegistrations(
    kit: KitWidgets | undefined,
    position: number,
    stock: (name: string) => NodeType[],
): Map<string, VocabularyRegistration[]> {
    const registry = createFrameRegistry({ widgets: kit });
    const out = new Map<string, VocabularyRegistration[]>();
    for (const { name, registrations } of registry.names()) {
        out.set(
            name,
            registrations.map(({ contexts, widget }) => {
                for (const context of contexts ?? []) {
                    if (!KNOWN.has(context)) {
                        throw new Error(
                            `kit ${position + 1}: "${name}" is registered for the context "${context}", which frame does not know (${KNOWN_CONTEXTS.join(', ')}).`,
                        );
                    }
                }
                return {
                    ...(contexts === null ? {} : { contexts: [...contexts] as FrameContext[] }),
                    ...(typeof widget === 'string' ? { stock: stock(widget) } : {}),
                };
            }),
        );
    }
    return out;
}

const same = (a: VocabularyRegistration, b: VocabularyRegistration) => JSON.stringify(a) === JSON.stringify(b);

/** What answers for a name in a context: the first registration scoped to it, else the first unscoped one (01). */
function answerIn(registrations: VocabularyRegistration[], context: FrameContext): VocabularyRegistration | undefined {
    return (
        registrations.find((r) => r.contexts?.includes(context)) ?? registrations.find((r) => r.contexts === undefined)
    );
}

/** Two answers differ when one is a component and the other a stock name, or two stock names differ in node types. */
function answersDiffer(a: VocabularyRegistration, b: VocabularyRegistration): boolean {
    if ((a.stock === undefined) !== (b.stock === undefined)) return true;
    return a.stock !== undefined && JSON.stringify(a.stock) !== JSON.stringify(b.stock);
}

/**
 * The vocabulary of one or more kits. Each kit's registry is built separately with `createFrameRegistry`, never
 * merged. `widgets` is the union (the first kit's registrations in winning order, then any a later kit adds), and
 * `conflicts` names where kits disagree. No argument, or `[]`, is the default kit.
 */
export function buildVocabulary(
    kits: Array<KitWidgets | undefined> = [],
    readers: readonly string[] = [],
): FrameVocabulary {
    const stock = stockTypesFor(createRjsfRegistry({ rootSchema: {} }).widgets);
    const perKit = (kits.length === 0 ? [undefined] : kits).map((kit, i) => kitRegistrations(kit, i, stock));

    const widgets: Record<string, VocabularyRegistration[]> = {};
    for (const kit of perKit) {
        for (const [name, registrations] of kit) {
            const union = (widgets[name] ??= []);
            for (const registration of registrations) {
                if (!union.some((r) => same(r, registration))) union.push(registration);
            }
        }
    }

    const conflicts: Record<string, FrameContext[]> = {};
    for (const name of Object.keys(widgets)) {
        const differing = KNOWN_CONTEXTS.filter((context) => {
            const answers = perKit
                .map((kit) => (kit.has(name) ? answerIn(kit.get(name)!, context) : undefined))
                .filter((answer): answer is VocabularyRegistration => answer !== undefined);
            // Every pair of kits that bind the name here.
            return answers.some((a, i) => answers.slice(i + 1).some((b) => answersDiffer(a, b)));
        });
        if (differing.length > 0) conflicts[name] = differing;
    }

    return {
        $comment: COMMENT,
        version: 1,
        contexts: [...KNOWN_CONTEXTS],
        formModes: [...FORM_MODES],
        reserved: [...RESERVED],
        widgets,
        reads: [...new Set([...FRAME_READS, ...readers])].sort(),
        ...(Object.keys(conflicts).length > 0 ? { conflicts } : {}),
    };
}

/** Keys sorted at every level; arrays keep their (meaningful) order. */
function sortKeys(value: unknown): unknown {
    if (Array.isArray(value)) return value.map(sortKeys);
    if (value && typeof value === 'object') {
        return Object.fromEntries(
            Object.keys(value as Record<string, unknown>)
                .sort()
                .map((key) => [key, sortKeys((value as Record<string, unknown>)[key])]),
        );
    }
    return value;
}

/** The one serialiser: what is written and what is compared. */
export function serializeVocabulary(vocabulary: FrameVocabulary): string {
    return `${JSON.stringify(sortKeys(vocabulary), null, 4)}\n`;
}

export interface RunVocabularyOptions {
    /** Each `--widgets` value, one per kit. */
    widgets: string[];
    /** Each repeatable --readers module. */
    readers: string[];
    out: string;
    write: boolean;
    cwd: string;
    /** Loads a --widgets or --readers module: Vite for source, host exports resolution for a package. */
    load: (specifier: string) => Promise<unknown>;
    /** The command a mismatch names. */
    command?: string;
}

export interface RunVocabularyResult {
    exitCode: 0 | 1 | 2;
    message: string;
}

/** The bin's whole run: load each kit's module, build, then write or compare. */
export async function runVocabulary(options: RunVocabularyOptions): Promise<RunVocabularyResult> {
    const command = options.command ?? 'frame-vocabulary --write';
    const kits: KitWidgets[] = [];
    for (const specifier of options.widgets) {
        let loaded: unknown;
        try {
            loaded = await options.load(specifier);
        } catch (error) {
            const code = (error as { code?: string }).code;
            return {
                exitCode: 2,
                message: `frame-vocabulary: could not load --widgets ${specifier}${code ? ` (${code})` : ''} from ${options.cwd}: ${(error as Error).message}`,
            };
        }
        const kit = (loaded as { default?: unknown })?.default;
        if (typeof kit !== 'function') {
            return { exitCode: 2, message: `frame-vocabulary: --widgets ${specifier} has no function default export.` };
        }
        kits.push(kit as KitWidgets);
    }

    const reads: string[] = [];
    for (const specifier of options.readers) {
        let loaded: unknown;
        try {
            loaded = await options.load(specifier);
        } catch (error) {
            return { exitCode: 2, message: `frame-vocabulary: could not load --readers ${specifier} from ${options.cwd}: ${(error as Error).message}` };
        }
        const readers = (loaded as { default?: unknown })?.default;
        if (readers === null || typeof readers !== 'object' ||
            (Object.getPrototypeOf(readers) !== Object.prototype && Object.getPrototypeOf(readers) !== null) ||
            !Object.entries(readers).every(([key, reader]) =>
                /^(manifest|resource-entry|context-block|schema-keywords):[^\s:]+$/.test(key) && typeof reader === 'function')) {
            return { exitCode: 2, message: `frame-vocabulary: --readers ${specifier} must default-export a plain FrameReaders map of <group>:<key> to reader functions.` };
        }
        reads.push(...Object.keys(readers));
    }

    let next: string;
    try {
        next = serializeVocabulary(buildVocabulary(kits, reads));
    } catch (error) {
        return { exitCode: 2, message: `frame-vocabulary: ${(error as Error).message}` };
    }

    const out = isAbsolute(options.out) ? options.out : resolvePath(options.cwd, options.out);
    if (options.write) {
        mkdirSync(dirname(out), { recursive: true });
        writeFileSync(out, next);
        return { exitCode: 0, message: `frame-vocabulary: wrote ${out}` };
    }
    const current = existsSync(out) ? readFileSync(out, 'utf8') : undefined;
    if (current === undefined || current.trim() === '') {
        return { exitCode: 1, message: `frame-vocabulary: ${out} is missing or empty. Run \`${command}\`.` };
    }
    if (current === next) return { exitCode: 0, message: `frame-vocabulary: ${out} is current.` };
    return { exitCode: 1, message: `frame-vocabulary: ${out} differs from what the kits bind:\n${lineDiff(current, next)}\nRun \`${command}\`.` };
}

/** The differing lines, committed (-) against generated (+). */
function lineDiff(current: string, next: string): string {
    const a = current.split('\n');
    const b = next.split('\n');
    const out: string[] = [];
    for (let i = 0; i < Math.max(a.length, b.length); i++) {
        if (a[i] === b[i]) continue;
        if (a[i] !== undefined) out.push(`- ${a[i]}`);
        if (b[i] !== undefined) out.push(`+ ${b[i]}`);
    }
    return out.join('\n');
}
